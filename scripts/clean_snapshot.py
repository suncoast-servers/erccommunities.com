#!/usr/bin/env python3
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "snapshot"
CF_SCRIPT = re.compile(
    r"<script>\(function\(\)\{function c\(\)\{.*?challenge-platform.*?</script>",
    re.S,
)
CF_EMAIL = re.compile(
    r'<script data-cfasync="false" src="/cdn-cgi/scripts/[^"]+"></script>'
)
CHATWOOT_TAG = (
    '<!-- Suncoast Chatwoot (default off; enabled via Cloudflare Pages env vars) -->\n'
    '<link rel="stylesheet" href="/chatwoot-polish.css" />\n'
    '<script>\n'
    '  window.CHATWOOT_CONFIG = window.CHATWOOT_CONFIG || {\n'
    '    enabled: false,\n'
    '    baseUrl: "https://support.suncoastservers.com",\n'
    '    websiteToken: "",\n'
    '    launcherTitle: "Chat with ERC",\n'
    '    widgetColor: "#2563eb",\n'
    '    brandName: "ERC Communities",\n'
    '    polishCssUrl: "/chatwoot-polish.css",\n'
    '    showNudge: true,\n'
    '    greetingLines: [\n'
    '      "A person answers this chat, with AI as backup.",\n'
    '      "Our AI gives faster first answers — a person still reads every message.",\n'
    '    ],\n'
    '  };\n'
    '</script>\n'
    '<script src="/chatwoot.js" defer></script>\n'
)
WP_COMMENTS = re.compile(
    r"\n?<!-- (?:Dynamic page generated in .*?|Cached page generated by WP-Super-Cache on .*?|super cache) -->"
)


def main() -> None:
    cleaned = 0
    for html in ROOT.rglob("*.html"):
        text = html.read_text(encoding="utf-8", errors="replace")
        updated = CF_SCRIPT.sub("", text)
        updated = CF_EMAIL.sub("", updated)
        updated = WP_COMMENTS.sub("", updated)
        # Regenerating the snapshot drops our widget block, so re-add it (chatwoot.js / the CSS
        # are separate files and are never overwritten by the snapshot).
        if "/chatwoot.js" not in updated and "</body>" in updated:
            updated = updated.replace("</body>", CHATWOOT_TAG + "</body>", 1)
        if updated != text:
            html.write_text(updated, encoding="utf-8")
            cleaned += 1
            print(f"cleaned {html.relative_to(ROOT)}")
    print(f"cleaned {cleaned} html files")


if __name__ == "__main__":
    main()
