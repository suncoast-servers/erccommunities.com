#!/usr/bin/env python3
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "snapshot"
CF_SCRIPT = re.compile(
    r"<script>\(function\(\)\{function c\(\)\{.*?challenge-platform.*?</script>",
    re.S,
)
CF_EMAIL = re.compile(
    r'<script data-cfasync="false" src="/cdn-cgi/scripts/[^"]+"></script>'
)
WP_COMMENTS = re.compile(
    r"\n?<!-- (?:Dynamic page generated in .*?|Cached page generated by WP-Super-Cache on .*?|super cache) -->"
)


def main() -> None:
    cleaned = 0
    for html in ROOT.rglob("*.html"):
        text = html.read_text(encoding="utf-8", errors="replace")
        updated = CF_SCRIPT.sub("", text)
        updated = CF_EMAIL.sub("", updated)
        updated = WP_COMMENTS.sub("", updated)
        if updated != text:
            html.write_text(updated, encoding="utf-8")
            cleaned += 1
            print(f"cleaned {html.relative_to(ROOT)}")
    print(f"cleaned {cleaned} html files")


if __name__ == "__main__":
    main()
